/**
 * Main form of Invoice (cr679_invoice).
 *
 * New invoice: fills empty fields with defaults the user can still change before saving:
 * - issue date = today;
 * - due date = issue date + cr679_InvoicePaymentTermDays (follows the issue date until the user edits it);
 * - VAT rate = cr679_InvoiceVatRate.
 * VAT and gross amounts are calculated columns and fill in after saving.
 *
 * Any invoice: selecting the order sets the net amount to the sum of its active items (read-only on the form, so the
 * PDF lines always add up to the total) and fills an empty customer with the order's customer. An order of another
 * customer is flagged on the Order field, which blocks saving.
 *
 * Any invoice: selecting or changing the customer copies the buyer name, address and NIP (accounts only)
 * from the customer; the user can still correct them. A prefilled customer on a new invoice fills empty buyer fields.
 *
 * Any invoice: shows the state of the PDF generated by the Azure Function as a form notification:
 * - Failed: an error with the message the generator wrote to cr679_errormessage;
 * - Requested / Generating: information that the PDF is on its way (the form does not refresh by itself).
 *
 * Form registration: library cr679_invoicemain,
 *   OnLoad -> RentMaszyny.invoice.main.onLoad (pass execution context: yes)
 * Required on the form: cr679_documentstatus, cr679_errormessage (can be hidden), cr679_issuedate,
 * cr679_duedate, cr679_vatrate, cr679_orderid, cr679_netamount (read-only), cr679_customerid, cr679_customername, cr679_customeraddress, cr679_customernip.
 *
 * UX only: invoices created outside this form get no defaults; the generator then marks them Failed.
 */

import { addDays, sameDay, today } from "../shared/dates";
import { getOrderCustomer, getOrderNetAmount } from "../shared/order";
import { Invoice, InvoiceDocumentStatus } from "../shared/schema";
import { getLookupId, normalizeGuid, RecordReader } from "../shared/xrm";
import { getCustomerSnapshot, readInvoiceSettings } from "./invoice.helper";

const DOCUMENT_NOTIFICATION_ID = "cr679_invoice_document";
const DEFAULTS_NOTIFICATION_ID = "cr679_invoice_defaults";
const CUSTOMER_NOTIFICATION_ID = "cr679_invoice_customer";
const ORDER_NOTIFICATION_ID = "cr679_invoice_order";
const ORDER_CUSTOMER_NOTIFICATION_ID = "cr679_invoice_order_customer";
const FORM_TYPE_CREATE = 1;

// State of the create form, reset by applyDefaults (the library stays loaded between records).
let paymentTermDays: number | null = null;
// Due date this script set; if the field still holds it, the user has not edited it.
let autoDueDate: Date | null = null;

export async function onLoad(executionContext: Xrm.Events.EventContext): Promise<void> {
  const formContext = executionContext.getFormContext();
  showDocumentState(formContext);
  // Runs again after save and refresh, when the generator may have changed the status.
  formContext.data.addOnLoad(() => showDocumentState(formContext));

  formContext.getAttribute(Invoice.fields.customer)?.addOnChange(onCustomerChange);
  formContext.getAttribute(Invoice.fields.order)?.addOnChange(onOrderChange);

  if (formContext.ui.getFormType() === FORM_TYPE_CREATE) {
    const buyerName = formContext.getAttribute<Xrm.Attributes.StringAttribute>(Invoice.fields.customerName);
    const netAmount = formContext.getAttribute<Xrm.Attributes.NumberAttribute>(Invoice.fields.netAmount);
    await Promise.all([
      applyDefaults(formContext, Xrm.WebApi),
      // An order prefilled on a new invoice also sets an empty customer, which copies the buyer data.
      netAmount && netAmount.getValue() === null ? applyOrderData(formContext, Xrm.WebApi) : Promise.resolve(),
      buyerName && !buyerName.getValue() && currentCustomer(formContext) ? copyCustomerData(formContext, Xrm.WebApi) : Promise.resolve(),
    ]);
  }
}

export async function onCustomerChange(executionContext: Xrm.Events.EventContext): Promise<void> {
  const formContext = executionContext.getFormContext();
  await Promise.all([copyCustomerData(formContext, Xrm.WebApi), checkOrderCustomer(formContext, Xrm.WebApi)]);
}

export function onOrderChange(executionContext: Xrm.Events.EventContext): Promise<void> {
  return applyOrderData(executionContext.getFormContext(), Xrm.WebApi);
}

/**
 * Sets the net amount to the order's total and fills an empty customer from the order.
 * An empty order leaves the amount as it is.
 */
export async function applyOrderData(formContext: Xrm.FormContext, webApi: RecordReader): Promise<void> {
  formContext.ui.clearFormNotification(ORDER_NOTIFICATION_ID);
  clearOrderCustomerMismatch(formContext);
  const orderId = getLookupId(formContext, Invoice.fields.order);
  if (!orderId) {
    return;
  }

  let orderCustomer;
  let netAmount;
  try {
    [orderCustomer, netAmount] = await Promise.all([getOrderCustomer(webApi, orderId), getOrderNetAmount(webApi, orderId)]);
  } catch (error: unknown) {
    console.error("[RentMaszyny.invoice.main] Reading the order failed", error);
    formContext.ui.setFormNotification(
      "Nie udało się pobrać danych zamówienia. Wybierz zamówienie ponownie.",
      "WARNING",
      ORDER_NOTIFICATION_ID
    );
    return;
  }
  // The user may have picked another order while the requests were running.
  if (getLookupId(formContext, Invoice.fields.order) !== orderId) {
    return;
  }

  const amount = formContext.getAttribute<Xrm.Attributes.NumberAttribute>(Invoice.fields.netAmount);
  // The field is read-only on the form; read-only values are saved only with submit mode "always".
  amount?.setSubmitMode("always");
  amount?.setValue(netAmount);

  if (!orderCustomer) {
    return;
  }
  const customer = currentCustomer(formContext);
  if (!customer) {
    formContext.getAttribute<Xrm.Attributes.LookupAttribute>(Invoice.fields.customer)?.setValue([orderCustomer]);
    // setValue does not fire OnChange, so copy the buyer data here.
    await copyCustomerData(formContext, webApi);
  } else if (customer.id !== orderCustomer.id) {
    flagOrderCustomerMismatch(formContext);
  }
}

/** Flags an order that belongs to another customer than the one selected on the invoice. */
export async function checkOrderCustomer(formContext: Xrm.FormContext, webApi: RecordReader): Promise<void> {
  clearOrderCustomerMismatch(formContext);
  const orderId = getLookupId(formContext, Invoice.fields.order);
  const customer = currentCustomer(formContext);
  if (!orderId || !customer) {
    return;
  }
  try {
    const orderCustomer = await getOrderCustomer(webApi, orderId);
    if (orderCustomer && orderCustomer.id !== currentCustomer(formContext)?.id && getLookupId(formContext, Invoice.fields.order) === orderId) {
      flagOrderCustomerMismatch(formContext);
    }
  } catch (error: unknown) {
    // Fail open: the check is UX only.
    console.error("[RentMaszyny.invoice.main] Checking the order customer failed", error);
  }
}

function flagOrderCustomerMismatch(formContext: Xrm.FormContext): void {
  formContext
    .getControl<Xrm.Controls.LookupControl>(Invoice.fields.order)
    ?.setNotification("To zamówienie należy do innego klienta.", ORDER_CUSTOMER_NOTIFICATION_ID);
}

function clearOrderCustomerMismatch(formContext: Xrm.FormContext): void {
  formContext.getControl<Xrm.Controls.LookupControl>(Invoice.fields.order)?.clearNotification(ORDER_CUSTOMER_NOTIFICATION_ID);
}

/** Overwrites the buyer fields with the current customer's data. An empty customer leaves them as they are. */
export async function copyCustomerData(formContext: Xrm.FormContext, webApi: RecordReader): Promise<void> {
  formContext.ui.clearFormNotification(CUSTOMER_NOTIFICATION_ID);
  const customer = currentCustomer(formContext);
  if (!customer) {
    return;
  }

  let snapshot;
  try {
    snapshot = await getCustomerSnapshot(webApi, customer);
  } catch (error: unknown) {
    console.error("[RentMaszyny.invoice.main] Reading the customer failed", error);
    formContext.ui.setFormNotification(
      "Nie udało się pobrać danych klienta. Uzupełnij dane nabywcy ręcznie.",
      "WARNING",
      CUSTOMER_NOTIFICATION_ID
    );
    return;
  }
  // The user may have picked another customer while the request was running.
  if (!snapshot || currentCustomer(formContext)?.id !== customer.id) {
    return;
  }

  setText(formContext, Invoice.fields.customerName, snapshot.name);
  setText(formContext, Invoice.fields.customerAddress, snapshot.address);
  setText(formContext, Invoice.fields.customerNip, snapshot.nip);
  if (!snapshot.name || !snapshot.address) {
    formContext.ui.setFormNotification(
      "Klient nie ma uzupełnionej nazwy lub adresu. Uzupełnij dane nabywcy na fakturze albo na karcie klienta.",
      "WARNING",
      CUSTOMER_NOTIFICATION_ID
    );
  }
}

function currentCustomer(formContext: Xrm.FormContext): Xrm.LookupValue | null {
  const value = formContext.getAttribute<Xrm.Attributes.LookupAttribute>(Invoice.fields.customer)?.getValue();
  const first = value && value.length > 0 ? value[0] : null;
  return first?.id ? { ...first, id: normalizeGuid(first.id) } : null;
}

function setText(formContext: Xrm.FormContext, field: string, value: string | null): void {
  formContext.getAttribute<Xrm.Attributes.StringAttribute>(field)?.setValue(value);
}

export async function applyDefaults(formContext: Xrm.FormContext, webApi: RecordReader): Promise<void> {
  const issueDate = formContext.getAttribute<Xrm.Attributes.DateAttribute>(Invoice.fields.issueDate);
  const dueDate = formContext.getAttribute<Xrm.Attributes.DateAttribute>(Invoice.fields.dueDate);
  const vatRate = formContext.getAttribute<Xrm.Attributes.NumberAttribute>(Invoice.fields.vatRate);

  paymentTermDays = null;
  autoDueDate = null;
  if (issueDate && !issueDate.getValue()) {
    issueDate.setValue(today());
  }

  let settings;
  try {
    settings = await readInvoiceSettings(webApi);
  } catch (error: unknown) {
    // Fail open: the user can still fill the fields by hand; the generator rejects incomplete invoices.
    console.error("[RentMaszyny.invoice.main] Reading invoice settings failed", error);
    warn(formContext, "Nie udało się odczytać stawki VAT i terminu płatności. Uzupełnij je ręcznie.");
    return;
  }

  paymentTermDays = settings.paymentTermDays;
  if (vatRate && vatRate.getValue() === null && settings.vatRate !== null) {
    vatRate.setValue(settings.vatRate);
  }
  const issued = issueDate?.getValue() ?? null;
  if (dueDate && !dueDate.getValue() && issued && paymentTermDays !== null) {
    autoDueDate = addDays(issued, paymentTermDays);
    dueDate.setValue(autoDueDate);
  }

  issueDate?.addOnChange(onIssueDateChange);

  if (settings.vatRate === null || settings.paymentTermDays === null) {
    warn(formContext, "Brak konfiguracji stawki VAT lub terminu płatności. Uzupełnij brakujące pola ręcznie.");
  }
}

/** Keeps the due date in step with the issue date, unless the user has set the due date by hand. */
export function onIssueDateChange(executionContext: Xrm.Events.EventContext): void {
  const formContext = executionContext.getFormContext();
  const issueDate = formContext.getAttribute<Xrm.Attributes.DateAttribute>(Invoice.fields.issueDate);
  const dueDate = formContext.getAttribute<Xrm.Attributes.DateAttribute>(Invoice.fields.dueDate);
  if (!issueDate || !dueDate || paymentTermDays === null) {
    return;
  }

  const issued = issueDate.getValue();
  const due = dueDate.getValue();
  if (!issued || (due && !sameDay(due, autoDueDate))) {
    return;
  }
  autoDueDate = addDays(issued, paymentTermDays);
  dueDate.setValue(autoDueDate);
}

export function showDocumentState(formContext: Xrm.FormContext): void {
  formContext.ui.clearFormNotification(DOCUMENT_NOTIFICATION_ID);
  // An unsaved invoice shows the column default (Requested), but nothing has been sent to the generator yet.
  if (formContext.ui.getFormType() === FORM_TYPE_CREATE) {
    return;
  }

  const status = formContext.getAttribute<Xrm.Attributes.OptionSetAttribute>(Invoice.fields.documentStatus)?.getValue();
  if (status === InvoiceDocumentStatus.Failed) {
    const reason = formContext.getAttribute<Xrm.Attributes.StringAttribute>(Invoice.fields.errorMessage)?.getValue();
    const message = reason
      ? `Nie udało się wygenerować PDF: ${reason}`
      : "Nie udało się wygenerować PDF. Szczegóły zna administrator (Application Log).";
    formContext.ui.setFormNotification(message, "ERROR", DOCUMENT_NOTIFICATION_ID);
  } else if (status === InvoiceDocumentStatus.Requested || status === InvoiceDocumentStatus.Generating) {
    formContext.ui.setFormNotification(
      "Trwa generowanie PDF. Odśwież formularz za chwilę, aby zobaczyć dokument.",
      "INFO",
      DOCUMENT_NOTIFICATION_ID
    );
  }
}

function warn(formContext: Xrm.FormContext, message: string): void {
  formContext.ui.setFormNotification(message, "WARNING", DEFAULTS_NOTIFICATION_ID);
}
